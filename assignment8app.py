import streamlit as st
import joblib
import numpy as np
# Load model and scaler
model = joblib.load("modelrf.pkl")
st.set_page_config(page_title="Diabetes Prediction", page_icon="🩺")
st.title("🩺 Diabetes Prediction")
st.write("Enter the feature values below to predict the outcome.")
# User Inputs
Age = st.number_input("Age", min_value=18)
Pregnancies = st.number_input("Pregnancies", min_value=0)
Glucose = st.number_input("Glucose", min_value=0)
BloodPressure = st.number_input("BloodPressure", min_value=0)
SkinThickness = st.number_input("SkinThickness", min_value=0)
Insulin = st.number_input("Insulin", min_value=0.0, format="%.4f")
BMI = st.number_input("BMI", min_value=0.0, format="%.2f")
if st.button("Predict outcome"):
    input_data = np.array([[
        Age,
        Pregnancies,
        Glucose,
        BloodPressure,
        SkinThickness,
        Insulin,
        BMI
    ]])
    # Predict
    prediction = model.predict(input_data)
    # Display Result
    if prediction[0] == 1:
        st.error("🔴 Person has Diabetes")
    else:
        st.success("🟢 Person has NO Diabetes")

